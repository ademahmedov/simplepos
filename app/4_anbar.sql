alter table public.mehsullar add column if not exists anbar_izle boolean not null default false;
alter table public.mehsullar add column if not exists min_qaliq  numeric(10,2) not null default 0;

create table if not exists public.anbar_hereketleri (
  id         bigint generated by default as identity primary key,
  magaza_id  bigint not null default public.magazam() references public.magazalar(id) on delete cascade,
  mehsul_id  bigint not null,
  tarix      date not null default current_date,
  nov        text not null check (nov in ('Mədaxil','Silinmə','Sayım')),
  miqdar     numeric(10,2) not null,             -- mədaxil +, silinmə −, sayım ± fərq
  qiymet     numeric(12,2) check (qiymet is null or qiymet >= 0),   -- alış qiyməti (bir ədəd)
  techizatci text,
  qeyd       text,
  yaradildi  timestamptz not null default now(),
  foreign key (mehsul_id, magaza_id) references public.mehsullar(id, magaza_id) on delete cascade
);
create index if not exists anbar_hereketleri_mehsul on public.anbar_hereketleri(mehsul_id);

create table if not exists public.satis_qaytarmalari (
  id        bigint generated by default as identity primary key,
  magaza_id bigint not null default public.magazam() references public.magazalar(id) on delete cascade,
  satis_id  bigint not null,
  tarix     date not null default current_date,
  mebleg    numeric(12,2) not null check (mebleg >= 0),   -- satışın dəyərindən çıxılan
  geri_pul  numeric(12,2) not null default 0 check (geri_pul >= 0),   -- müştəriyə qaytarılan nağd
  mallar    text,
  qeyd      text,
  yaradildi timestamptz not null default now(),
  foreign key (satis_id, magaza_id) references public.satislar(id, magaza_id) on delete cascade
);
create index if not exists satis_qaytarmalari_satis on public.satis_qaytarmalari(satis_id);

do $$
declare t text;
begin
  foreach t in array array['anbar_hereketleri','satis_qaytarmalari']
  loop
    execute format('alter table public.%I enable row level security', t);
    execute format('drop policy if exists oxu on public.%I', t);
    execute format('drop policy if exists elave on public.%I', t);
    execute format('drop policy if exists duzelt on public.%I', t);
    execute format('drop policy if exists sil on public.%I', t);
    execute format($p$create policy oxu on public.%I for select to authenticated
      using (magaza_id = (select public.magazam()) and (select public.rolum()) in ('muhasib','sahibkar'))$p$, t);
    execute format($p$create policy elave on public.%I for insert to authenticated
      with check (magaza_id = (select public.magazam()) and (select public.rolum()) = 'muhasib' and (select public.aktivdir()))$p$, t);
    execute format($p$create policy duzelt on public.%I for update to authenticated
      using (magaza_id = (select public.magazam()) and (select public.rolum()) = 'muhasib' and (select public.aktivdir()))
      with check (magaza_id = (select public.magazam()))$p$, t);
    execute format($p$create policy sil on public.%I for delete to authenticated
      using (magaza_id = (select public.magazam()) and (select public.rolum()) = 'muhasib' and (select public.aktivdir()))$p$, t);
    execute format('drop trigger if exists jurnal_trg on public.%I', t);
    execute format('create trigger jurnal_trg after insert or update or delete on public.%I for each row execute function public.jurnal_yaz()', t);
    execute format('grant select, insert, update, delete on public.%I to authenticated', t);
  end loop;
end $$;
grant usage, select on all sequences in schema public to authenticated;

-- Məhsullar: satış sayı + anbar qalığı (mədaxil ± hərəkətlər − satılan)
drop view if exists public.v_mehsullar;
create view public.v_mehsullar with (security_invoker = true) as
select m.*, coalesce(x.miqdar, 0) as satilib, coalesce(x.cem, 0) as satis_cemi, x.son as son_satis,
       coalesce(h.miqdar, 0) - coalesce(x.miqdar, 0) as anbar,
       h.son_alis
from public.mehsullar m
left join (select sm.mehsul_id, sum(sm.miqdar) miqdar, sum(sm.miqdar * sm.qiymet) cem, max(s.tarix) son
           from public.satis_mallari sm join public.satislar s on s.id = sm.satis_id
           group by sm.mehsul_id) x on x.mehsul_id = m.id
left join (select mehsul_id, sum(miqdar) miqdar, max(tarix) filter (where nov = 'Mədaxil') son_alis
           from public.anbar_hereketleri group by mehsul_id) h on h.mehsul_id = m.id;
grant select on public.v_mehsullar to authenticated;

-- Qalıq borc: dəyər − ilkin − ödənişlər + cərimə + qaytarılan nağd (yeni sütun "geri" sonda)
create or replace view public.v_satislar with (security_invoker = true) as
select s.id, s.satis_no, s.tarix, s.musteri_id, m.ad as musteri, m.unvan, m.telefon,
       s.mal, s.deyer, s.ilkin, s.qeyd,
       coalesce(p.cem, 0)                                          as odenilen,
       s.deyer - s.ilkin - coalesce(p.cem, 0) + coalesce(c.cem, 0) + coalesce(g.cem, 0) as qaliq,
       coalesce(p.say, 0)                                          as odenis_sayi,
       p.son                                                       as son_odenis,
       date_trunc('month', s.tarix)::date                          as ay,
       s.magaza_id,
       coalesce(c.cem, 0)                                          as cerime,
       coalesce(g.cem, 0)                                          as geri
from public.satislar s
join public.musteriler m on m.id = s.musteri_id
left join (select satis_id, sum(mebleg) cem, count(*) say, max(tarix) son
           from public.satis_odenisleri group by satis_id) p on p.satis_id = s.id
left join (select satis_id, sum(mebleg) cem from public.satis_cerimeleri group by satis_id) c on c.satis_id = s.id
left join (select satis_id, sum(geri_pul) cem from public.satis_qaytarmalari group by satis_id) g on g.satis_id = s.id;

create or replace view public.v_musteriler with (security_invoker = true) as
with p as (
  select satis_id, sum(mebleg) cem, max(tarix) son from public.satis_odenisleri group by satis_id
), c as (
  select satis_id, sum(cem) cem from (
    select satis_id, mebleg cem from public.satis_cerimeleri
    union all select satis_id, geri_pul from public.satis_qaytarmalari) x group by satis_id
), s as (
  select s.musteri_id, s.tarix, s.deyer, p.son,
         s.deyer - s.ilkin - coalesce(p.cem, 0) + coalesce(c.cem, 0) as qaliq,
         case when s.deyer - s.ilkin - coalesce(p.cem, 0) + coalesce(c.cem, 0) > 0 then
           case when s.ayliq is not null and s.ilk_odenis is not null
                then current_date - (s.ilk_odenis + make_interval(months => floor(coalesce(p.cem,0) / s.ayliq)::int))::date
                else current_date - (greatest(s.tarix, coalesce(p.son, s.tarix)) + 30) end
         end as gec
  from public.satislar s left join p on p.satis_id = s.id left join c on c.satis_id = s.id
)
select m.id, m.ad, m.unvan, m.telefon, m.qeyd,
       count(s.musteri_id)                 as satis_sayi,
       min(s.tarix)                        as ilk_satis,
       coalesce(sum(s.deyer), 0)           as cem,
       coalesce(sum(s.deyer - s.qaliq), 0) as verilen,
       coalesce(sum(s.qaliq), 0)           as qaliq,
       greatest(max(s.tarix), max(s.son))  as son_tarix,
       max(s.gec)                          as gecikme_gun,
       m.magaza_id
from public.musteriler m
left join s on s.musteri_id = m.id
group by m.id;

create or replace view public.v_aylar with (security_invoker = true) as
with mg as (
  select m.id as magaza_id,
         coalesce((select nullif(deyer, '')::date from public.ayarlar a where a.magaza_id = m.id and a.acar = 'kassa_baslangic'),
                  (select date_trunc('month', min(tarix))::date from public.satislar s where s.magaza_id = m.id),
                  date_trunc('month', current_date)::date) as d
  from public.magazalar m
), aylar as (
  select mg.magaza_id, generate_series(date_trunc('month', mg.d), date_trunc('month', current_date), interval '1 month')::date as ay from mg
), p as (
  select satis_id, sum(mebleg) cem from public.satis_odenisleri group by satis_id
), c as (
  select satis_id, sum(cem) cem from (
    select satis_id, mebleg cem from public.satis_cerimeleri
    union all select satis_id, geri_pul from public.satis_qaytarmalari) x group by satis_id
), st as (
  select s.magaza_id, date_trunc('month', s.tarix)::date ay, sum(s.deyer) satis, count(*) say, sum(s.ilkin) ilkin,
         sum(s.deyer - s.ilkin - coalesce(p.cem, 0) + coalesce(c.cem, 0)) qalan
  from public.satislar s left join p on p.satis_id = s.id left join c on c.satis_id = s.id group by 1, 2
), od as (
  select magaza_id, date_trunc('month', tarix)::date ay, sum(mebleg) c from public.satis_odenisleri group by 1, 2
), kd as (
  select magaza_id, date_trunc('month', tarix)::date ay,
         sum(mebleg) filter (where nov = 'Mədaxil') med, sum(mebleg) filter (where nov = 'Məxaric') mex
  from public.kassa_diger group by 1, 2
), rx as (
  select magaza_id, date_trunc('month', tarix)::date ay, sum(mebleg) c from public.rasxodlar group by 1, 2
), io as (
  select o.magaza_id, date_trunc('month', o.tarix)::date ay,
         sum(o.mebleg) filter (where i.nov = 'İşçi') maas, sum(o.mebleg) filter (where i.nov = 'Sahib') sahib
  from public.isci_odenisleri o join public.isciler i on i.id = o.isci_id
  where o.nov in ('Avans','Maaş') group by 1, 2
)
select a.ay,
  coalesce(st.satis, 0) as satis,
  coalesce(st.say, 0)   as satis_sayi,
  coalesce(st.qalan, 0) as satisdan_qalan,
  coalesce(st.ilkin, 0) as ilkin,
  coalesce(od.c, 0)     as musteri_odenisi,
  coalesce(kd.med, 0)   as diger_medaxil,
  coalesce(rx.c, 0)     as rasxod,
  coalesce(io.maas, 0)  as maas,
  coalesce(io.sahib, 0) as sahib,
  coalesce(kd.mex, 0)   as diger_mexaric,
  a.magaza_id
from aylar a
left join st on st.magaza_id = a.magaza_id and st.ay = a.ay
left join od on od.magaza_id = a.magaza_id and od.ay = a.ay
left join kd on kd.magaza_id = a.magaza_id and kd.ay = a.ay
left join rx on rx.magaza_id = a.magaza_id and rx.ay = a.ay
left join io on io.magaza_id = a.magaza_id and io.ay = a.ay;

