create or replace view public.v_satislar with (security_invoker = true) as
select s.id, s.satis_no, s.tarix, s.musteri_id, m.ad as musteri, m.unvan, m.telefon,
       s.mal, s.deyer, s.ilkin, s.qeyd,
       coalesce(p.cem, 0)                     as odenilen,
       s.deyer - s.ilkin - coalesce(p.cem, 0) as qaliq,
       coalesce(p.say, 0)                     as odenis_sayi,
       p.son                                  as son_odenis,
       date_trunc('month', s.tarix)::date     as ay,
       s.magaza_id
from public.satislar s
join public.musteriler m on m.id = s.musteri_id
left join (select satis_id, sum(mebleg) cem, count(*) say, max(tarix) son
           from public.satis_odenisleri group by satis_id) p on p.satis_id = s.id;

create or replace view public.v_qrafik with (security_invoker = true) as
select v.id, v.musteri_id, s.ayliq, s.ilk_odenis, s.maya,
       v.deyer - v.ilkin as kredit, v.odenilen, v.qaliq,
       (s.ayliq is not null and s.ilk_odenis is not null) as qrafikli,
       case when s.ayliq > 0 then ceil((v.deyer - v.ilkin) / s.ayliq)::int end as odenis_sayi,
       case when s.ayliq > 0 and s.ilk_odenis is not null
            then least(v.deyer - v.ilkin, s.ayliq * n.n) end as gozlenilen,
       case when s.ayliq > 0 and s.ilk_odenis is not null
            then greatest(0, least(v.deyer - v.ilkin, s.ayliq * n.n) - v.odenilen) end as gecikmis,
       case when s.ayliq > 0 and s.ilk_odenis is not null and v.qaliq > 0
            then (s.ilk_odenis + make_interval(months => floor(v.odenilen / s.ayliq)::int))::date end as novbeti_tarix,
       case when s.ayliq > 0 and s.ilk_odenis is not null and v.qaliq > 0
            then least(s.ayliq * (floor(v.odenilen / s.ayliq) + 1), v.deyer - v.ilkin) - v.odenilen end as novbeti_mebleg,
       s.magaza_id
from public.v_satislar v
join public.satislar s on s.id = v.id
cross join lateral (
  select case when s.ilk_odenis is null or s.ilk_odenis > current_date then 0
              else (extract(year from age(current_date, s.ilk_odenis)) * 12
                  + extract(month from age(current_date, s.ilk_odenis)))::int + 1 end as n
) n;

create or replace view public.v_musteriler with (security_invoker = true) as
with p as (
  select satis_id, sum(mebleg) cem, max(tarix) son from public.satis_odenisleri group by satis_id
), s as (
  select s.musteri_id, s.tarix, s.deyer, p.son,
         s.deyer - s.ilkin - coalesce(p.cem, 0) as qaliq,
         case when s.deyer - s.ilkin - coalesce(p.cem, 0) > 0 then
           case when s.ayliq is not null and s.ilk_odenis is not null
                then current_date - (s.ilk_odenis + make_interval(months => floor(coalesce(p.cem,0) / s.ayliq)::int))::date
                else current_date - (greatest(s.tarix, coalesce(p.son, s.tarix)) + 30) end
         end as gec
  from public.satislar s left join p on p.satis_id = s.id
)
select m.id, m.ad, m.unvan, m.telefon, m.qeyd,
       count(s.musteri_id)                 as satis_sayi,
       min(s.tarix)                        as ilk_satis,
       coalesce(sum(s.deyer), 0)           as cem,
       coalesce(sum(s.deyer - s.qaliq), 0) as verilen,
       coalesce(sum(s.qaliq), 0)           as qaliq,
       greatest(max(s.tarix), max(s.son))  as son_tarix,
       max(s.gec)                          as gecikme_gun,
       m.magaza_id
from public.musteriler m
left join s on s.musteri_id = m.id
group by m.id;

create or replace view public.v_aylar with (security_invoker = true) as
with mg as (
  select m.id as magaza_id,
         coalesce((select nullif(deyer, '')::date from public.ayarlar a where a.magaza_id = m.id and a.acar = 'kassa_baslangic'),
                  (select date_trunc('month', min(tarix))::date from public.satislar s where s.magaza_id = m.id),
                  date_trunc('month', current_date)::date) as d
  from public.magazalar m
), aylar as (
  select mg.magaza_id, generate_series(date_trunc('month', mg.d), date_trunc('month', current_date), interval '1 month')::date as ay from mg
), p as (
  select satis_id, sum(mebleg) cem from public.satis_odenisleri group by satis_id
), st as (
  select s.magaza_id, date_trunc('month', s.tarix)::date ay, sum(s.deyer) satis, count(*) say, sum(s.ilkin) ilkin,
         sum(s.deyer - s.ilkin - coalesce(p.cem, 0)) qalan
  from public.satislar s left join p on p.satis_id = s.id group by 1, 2
), od as (
  select magaza_id, date_trunc('month', tarix)::date ay, sum(mebleg) c from public.satis_odenisleri group by 1, 2
), kd as (
  select magaza_id, date_trunc('month', tarix)::date ay,
         sum(mebleg) filter (where nov = 'Mədaxil') med, sum(mebleg) filter (where nov = 'Məxaric') mex
  from public.kassa_diger group by 1, 2
), rx as (
  select magaza_id, date_trunc('month', tarix)::date ay, sum(mebleg) c from public.rasxodlar group by 1, 2
), io as (
  select o.magaza_id, date_trunc('month', o.tarix)::date ay,
         sum(o.mebleg) filter (where i.nov = 'İşçi') maas, sum(o.mebleg) filter (where i.nov = 'Sahib') sahib
  from public.isci_odenisleri o join public.isciler i on i.id = o.isci_id
  where o.nov in ('Avans','Maaş') group by 1, 2
)
select a.ay,
  coalesce(st.satis, 0) as satis,
  coalesce(st.say, 0)   as satis_sayi,
  coalesce(st.qalan, 0) as satisdan_qalan,
  coalesce(st.ilkin, 0) as ilkin,
  coalesce(od.c, 0)     as musteri_odenisi,
  coalesce(kd.med, 0)   as diger_medaxil,
  coalesce(rx.c, 0)     as rasxod,
  coalesce(io.maas, 0)  as maas,
  coalesce(io.sahib, 0) as sahib,
  coalesce(kd.mex, 0)   as diger_mexaric,
  a.magaza_id
from aylar a
left join st on st.magaza_id = a.magaza_id and st.ay = a.ay
left join od on od.magaza_id = a.magaza_id and od.ay = a.ay
left join kd on kd.magaza_id = a.magaza_id and kd.ay = a.ay
left join rx on rx.magaza_id = a.magaza_id and rx.ay = a.ay
left join io on io.magaza_id = a.magaza_id and io.ay = a.ay;

create or replace view public.v_kassa with (security_invoker = true) as
select x.*,
  x.ilkin + x.musteri_odenisi + x.diger_medaxil         as medaxil,
  x.rasxod + x.maas + x.sahib + x.diger_mexaric         as mexaric,
  coalesce((select nullif(deyer, '')::numeric from public.ayarlar a where a.magaza_id = x.magaza_id and a.acar = 'kassa_ilkin'), 0)
   + sum(x.ilkin + x.musteri_odenisi + x.diger_medaxil - x.rasxod - x.maas - x.sahib - x.diger_mexaric)
       over (partition by x.magaza_id order by x.ay)   as ay_sonu_kassa
from public.v_aylar x;

create or replace view public.v_rasxod_kateqoriya with (security_invoker = true) as
select date_trunc('month', tarix)::date as ay, kateqoriya, sum(mebleg) as cem, count(*) as say, magaza_id
from public.rasxodlar group by magaza_id, 1, 2;

create or replace view public.v_isci_dovrleri with (security_invoker = true) as
select i.id as isci_id, g.n as dovr,
       (i.ise_giris + make_interval(months => g.n - 1))::date as tarix,
       coalesce((select d.maas from public.maas_deyisiklikleri d
                 where d.isci_id = i.id
                   and d.tarixden <= (i.ise_giris + make_interval(months => g.n - 1))::date
                 order by d.tarixden desc, d.id desc limit 1), i.baslangic_maas) as maas,
       i.magaza_id
from public.isciler i
cross join lateral generate_series(1,
   case when i.ise_giris is null then 0
        else (extract(year  from age(least(current_date, coalesce(i.cixis, current_date)), i.ise_giris)) * 12
            + extract(month from age(least(current_date, coalesce(i.cixis, current_date)), i.ise_giris)))::int + 1
   end) as g(n)
where i.nov = 'İşçi';

create or replace view public.v_isciler with (security_invoker = true) as
select i.*,
  case when i.cixis is not null and i.cixis < current_date then 'Çıxıb' else 'İşləyir' end as status,
  coalesce((select d.maas from public.maas_deyisiklikleri d where d.isci_id = i.id
            order by d.tarixden desc, d.id desc limit 1), i.baslangic_maas) as cari_maas,
  coalesce((select count(*) from public.v_isci_dovrleri v where v.isci_id = i.id), 0) as dovr_sayi,
  coalesce((select sum(maas) from public.v_isci_dovrleri v where v.isci_id = i.id), 0) as hesablanan,
  coalesce((select sum(mebleg) from public.isci_odenisleri o where o.isci_id = i.id and o.nov = 'Bonus'), 0) as bonus,
  coalesce((select sum(mebleg) from public.isci_odenisleri o where o.isci_id = i.id and o.nov = 'Cərimə'), 0) as cerime,
  coalesce((select sum(mebleg) from public.isci_odenisleri o where o.isci_id = i.id and o.nov in ('Avans','Maaş')), 0) as goturduyu,
  case when i.nov = 'Sahib' then null else
    coalesce((select sum(maas) from public.v_isci_dovrleri v where v.isci_id = i.id), 0)
  + coalesce((select sum(mebleg) from public.isci_odenisleri o where o.isci_id = i.id and o.nov = 'Bonus'), 0)
  - coalesce((select sum(mebleg) from public.isci_odenisleri o where o.isci_id = i.id and o.nov = 'Cərimə'), 0)
  - coalesce((select sum(mebleg) from public.isci_odenisleri o where o.isci_id = i.id and o.nov in ('Avans','Maaş')), 0)
  end as verilecek,
  case when i.nov = 'Sahib' or i.ise_giris is null or (i.cixis is not null and i.cixis < current_date) then null
       else (i.ise_giris + make_interval(months =>
              (select count(*)::int from public.v_isci_dovrleri v where v.isci_id = i.id)))::date
  end as novbeti_maas_gunu
from public.isciler i;

