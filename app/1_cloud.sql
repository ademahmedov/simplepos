  yaradildi  timestamptz not null default now()
);
create index if not exists uzvler_magaza on public.uzvler(magaza_id);

create table if not exists public.adminler (
  user_id uuid primary key references auth.users(id) on delete cascade
);

create table if not exists public.sistem (
