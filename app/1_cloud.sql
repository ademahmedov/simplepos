create table if not exists public.magazalar (
  id            bigint generated by default as identity primary key,
  ad            text not null,
  sahib_ad      text,
  telefon       text,
  email         text,
  qeydiyyat     timestamptz not null default now(),
  abune_bitir   date not null default ((now() at time zone 'Asia/Baku')::date + 14),
  dayandirilib  boolean not null default false,
  devet_kodu    text not null unique default upper(substr(md5(random()::text || clock_timestamp()::text), 1, 6)),
  admin_qeyd    text
);

create table if not exists public.uzvler (
  user_id    uuid primary key references auth.users(id) on delete cascade,
  magaza_id  bigint not null references public.magazalar(id) on delete cascade,
  rol        text not null default 'sahibkar' check (rol in ('muhasib','sahibkar','bloklu')),
  ad         text,
