create or replace function public.devet_yenile() returns text
language plpgsql security definer set search_path = public as $$
declare k text;
begin
  if public.rolum() is distinct from 'muhasib' then raise exception 'İcazə yoxdur'; end if;
  k := upper(substr(md5(random()::text || clock_timestamp()::text), 1, 6));
  update public.magazalar set devet_kodu = k where id = public.magazam();
  return k;
end $$;

