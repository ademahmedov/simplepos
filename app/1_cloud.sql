-- ---------------------------------------------------------------------
--  Qeydiyyat: yeni istifadəçi → yeni dükan, və ya dəvət kodu ilə mövcud dükana
-- ---------------------------------------------------------------------
create or replace function public.magaza_hazirla(m bigint) returns void
language sql security definer set search_path = public as $$
  insert into public.ayarlar(magaza_id, acar, deyer)
  select m, k, v from (values
    ('firma_adi', (select ad from public.magazalar where id = m)),
    ('firma_unvan', ''), ('firma_telefon', (select coalesce(telefon, '') from public.magazalar where id = m)), ('firma_voen', ''),
    ('muqavile_sertleri', 'Alıcı qrafikdə göstərilən məbləğləri vaxtında ödəməyi öhdəsinə götürür. Ödənişlər tam başa çatana qədər mal satıcının mülkiyyətində qalır.'),
    ('kassa_ilkin', '0')) x(k, v)
  on conflict do nothing;
$$;

create or replace function public.yeni_istifadeci() returns trigger
language plpgsql security definer set search_path = public as $f$
declare md jsonb := coalesce(new.raw_user_meta_data, '{}'::jsonb); m bigint; kod text;
begin
  kod := upper(trim(coalesce(md->>'devet_kodu', '')));
  if kod <> '' then
    select id into m from public.magazalar where devet_kodu = kod;
    if m is null then raise exception 'Dəvət kodu səhvdir'; end if;
    insert into public.uzvler(user_id, magaza_id, rol, ad, email)
      values (new.id, m, 'sahibkar', nullif(trim(md->>'ad'), ''), new.email);
  elsif coalesce(trim(md->>'magaza_adi'), '') <> '' then
    insert into public.magazalar(ad, sahib_ad, telefon, email, abune_bitir)
      values (trim(md->>'magaza_adi'), nullif(trim(md->>'ad'), ''), nullif(trim(md->>'telefon'), ''), new.email,
              public.bugun() + coalesce((select deyer::int from public.sistem where acar = 'sinaq_gun'), 14))
      returning id into m;
    insert into public.uzvler(user_id, magaza_id, rol, ad, email)
      values (new.id, m, 'muhasib', nullif(trim(md->>'ad'), ''), new.email);
    perform public.magaza_hazirla(m);
  end if;
  return new;
end $f$;
drop trigger if exists yeni_istifadeci_trg on auth.users;
create trigger yeni_istifadeci_trg after insert on auth.users for each row execute function public.yeni_istifadeci();

