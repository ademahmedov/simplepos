-- Köməkçi funksiyalar (giriş yoxlaması üçün)
create or replace function public.magazam() returns bigint
language sql stable security definer set search_path = public as $$
  select magaza_id from public.uzvler where user_id = auth.uid()
$$;
create or replace function public.rolum() returns text
language sql stable security definer set search_path = public as $$
  select rol from public.uzvler where user_id = auth.uid()
$$;
create or replace function public.adminem() returns boolean
language sql stable security definer set search_path = public as $$
  select exists (select 1 from public.adminler where user_id = auth.uid())
$$;
create or replace function public.bugun() returns date
language sql stable as $$ select (now() at time zone 'Asia/Baku')::date $$;
create or replace function public.aktivdir(m bigint default null) returns boolean
language sql stable security definer set search_path = public as $$
  select coalesce((select not dayandirilib and abune_bitir >= public.bugun()
                   from public.magazalar where id = coalesce(m, public.magazam())), false)
$$;

