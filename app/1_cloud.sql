create or replace function public.admin_magazalar()
returns table(id bigint, ad text, sahib_ad text, telefon text, email text, qeydiyyat timestamptz,
              abune_bitir date, dayandirilib boolean, admin_qeyd text, aktiv boolean,
              uzv_sayi bigint, musteri_sayi bigint, satis_sayi bigint, son_aktivlik timestamptz)
language plpgsql stable security definer set search_path = public as $f$
begin
  if not public.adminem() then raise exception 'İcazə yoxdur'; end if;
  return query
  select m.id, m.ad, m.sahib_ad, m.telefon, m.email, m.qeydiyyat, m.abune_bitir, m.dayandirilib, m.admin_qeyd,
         (not m.dayandirilib and m.abune_bitir >= public.bugun()),
         (select count(*) from uzvler u where u.magaza_id = m.id),
         (select count(*) from musteriler x where x.magaza_id = m.id),
         (select count(*) from satislar x where x.magaza_id = m.id),
         (select max(j.zaman) from jurnal j where j.magaza_id = m.id)
  from magazalar m order by m.qeydiyyat desc;
end $f$;

create or replace function public.admin_uzat(m bigint, aylar int) returns date
language plpgsql security definer set search_path = public as $f$
declare d date;
begin
  if not public.adminem() then raise exception 'İcazə yoxdur'; end if;
  update magazalar set abune_bitir = (greatest(abune_bitir, public.bugun()) + make_interval(months => aylar))::date,
                       dayandirilib = false
   where id = m returning abune_bitir into d;
  return d;
end $f$;

create or replace function public.admin_deyis(m bigint, bitir date, dayan boolean, qeyd text) returns void
language plpgsql security definer set search_path = public as $f$
begin
  if not public.adminem() then raise exception 'İcazə yoxdur'; end if;
  update magazalar set abune_bitir = coalesce(bitir, abune_bitir), dayandirilib = coalesce(dayan, dayandirilib),
                       admin_qeyd = coalesce(qeyd, admin_qeyd) where id = m;
end $f$;

