create or replace function public.satis_no_ver() returns trigger
language plpgsql security definer set search_path = public as $$
begin
  if new.satis_no is null or new.satis_no = '' then
    perform pg_advisory_xact_lock(new.magaza_id);
    select 'Sat' || lpad((coalesce(max(substring(satis_no from 4)::int), 0) + 1)::text, 4, '0')
      into new.satis_no from public.satislar where magaza_id = new.magaza_id and satis_no ~ '^Sat[0-9]+$';
  end if;
  return new;
end $$;
drop trigger if exists satis_no_trg on public.satislar;
create trigger satis_no_trg before insert on public.satislar for each row execute function public.satis_no_ver();

