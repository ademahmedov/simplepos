-- Kontragentlər (VÖEN reyestri)
create table if not exists public.kontragentler (
  id         bigint generated by default as identity primary key,
  magaza_id  bigint not null default public.magazam() references public.magazalar(id) on delete cascade,
  voen       text,
  ad         text not null,
  unvan      text,
  telefon    text,
  hesab      text,
  qeyd       text,
  yaradildi  timestamptz not null default now(),
  unique (id, magaza_id)
);
create unique index if not exists kontragentler_voen on public.kontragentler(magaza_id, voen) where voen is not null and voen <> '';

-- Qaimələr: gələn (alış) və gedən (satış)
create table if not exists public.qaimeler (
  id          bigint generated by default as identity primary key,
  magaza_id   bigint not null default public.magazam() references public.magazalar(id) on delete cascade,
  istiqamet   text not null check (istiqamet in ('gelen','geden')),
  voen        text,
  kontragent  text,
  seriya      text,
  nomre       text,
  tarix       date not null,
  esas        numeric(14,2) not null default 0 check (esas >= 0),
  edv         numeric(14,2) not null default 0 check (edv >= 0),
  edvsiz      numeric(14,2) not null default 0 check (edvsiz >= 0),
  status      text,
  qeyd        text,
  yaradildi   timestamptz not null default now(),
  unique (id, magaza_id)
);
create unique index if not exists qaimeler_tekrar on public.qaimeler(magaza_id, istiqamet, coalesce(seriya, ''), coalesce(nomre, ''), coalesce(voen, ''));
create index if not exists qaimeler_tarix on public.qaimeler(magaza_id, istiqamet, tarix);

-- Bank hesabları və əməliyyatları
create table if not exists public.bank_hesablari (
  id          bigint generated by default as identity primary key,
  magaza_id   bigint not null default public.magazam() references public.magazalar(id) on delete cascade,
  bank        text not null,
  hesab_no    text,
  valyuta     text not null default 'AZN',
  ilkin_qaliq numeric(14,2) not null default 0,
  ilkin_tarix date,
  edv_depozit boolean not null default false,
  aktiv       boolean not null default true,
  yaradildi   timestamptz not null default now(),
  unique (id, magaza_id)
);

-- Qaimələrin ödənişi (hissə-hissə, aylar üzrə). edv = ödənişin ƏDV hissəsi
create table if not exists public.qaime_odenisleri (
  id         bigint generated by default as identity primary key,
  magaza_id  bigint not null default public.magazam() references public.magazalar(id) on delete cascade,
  qaime_id   bigint not null,
  tarix      date not null,
  mebleg     numeric(14,2) not null check (mebleg > 0),
  edv        numeric(14,2) not null default 0 check (edv >= 0),
  hesab_id   bigint,
  qeyd       text,
  yaradildi  timestamptz not null default now(),
  foreign key (qaime_id, magaza_id) references public.qaimeler(id, magaza_id) on delete cascade,
  foreign key (hesab_id, magaza_id) references public.bank_hesablari(id, magaza_id) on delete set null (hesab_id)
);
create index if not exists qaime_odenisleri_qaime on public.qaime_odenisleri(qaime_id);

create table if not exists public.bank_emeliyyatlari (
  id          bigint generated by default as identity primary key,
  magaza_id   bigint not null default public.magazam() references public.magazalar(id) on delete cascade,
  hesab_id    bigint not null,
  tarix       date not null,
  nov         text not null check (nov in ('Mədaxil','Məxaric')),
  mebleg      numeric(14,2) not null check (mebleg > 0),
  kateqoriya  text,
  voen        text,
  kontragent  text,
  teyinat     text,
  yaradildi   timestamptz not null default now(),
  foreign key (hesab_id, magaza_id) references public.bank_hesablari(id, magaza_id) on delete cascade
);
create index if not exists bank_emeliyyatlari_hesab on public.bank_emeliyyatlari(hesab_id, tarix);

-- İdxal / ixrac (gömrük bəyannamələri)
create table if not exists public.gomruk (
  id             bigint generated by default as identity primary key,
  magaza_id      bigint not null default public.magazam() references public.magazalar(id) on delete cascade,
  nov            text not null check (nov in ('idxal','ixrac')),
  tarix          date not null,
  beyanname      text,
  terefdas       text,
  olke           text,
  valyuta        text default 'USD',
  mebleg_valyuta numeric(14,2),
  mezenne        numeric(12,4),
  gomruk_deyeri  numeric(14,2) not null default 0 check (gomruk_deyeri >= 0),
  rusum          numeric(14,2) not null default 0 check (rusum >= 0),
  edv            numeric(14,2) not null default 0 check (edv >= 0),
  diger          numeric(14,2) not null default 0 check (diger >= 0),
  qeyd           text,
  yaradildi      timestamptz not null default now()
);

-- Əmək haqqı: əməkdaşlar və aylıq hesablamalar
create table if not exists public.emekdaslar (
  id         bigint generated by default as identity primary key,
  magaza_id  bigint not null default public.magazam() references public.magazalar(id) on delete cascade,
  ad         text not null,
  fin        text,
  vezife     text,
  maas       numeric(12,2) not null default 0 check (maas >= 0),
  esas_is    boolean not null default true,
  ise_qebul  date,
  cixis      date,
  qeyd       text,
  yaradildi  timestamptz not null default now(),
  unique (id, magaza_id)
);
create table if not exists public.emek_haqqi (
  id             bigint generated by default as identity primary key,
  magaza_id      bigint not null default public.magazam() references public.magazalar(id) on delete cascade,
  emekdas_id     bigint not null,
  ay             date not null,
  hesablanan     numeric(12,2) not null default 0,
  gelir_vergisi  numeric(12,2) not null default 0,
  dsmf_isci      numeric(12,2) not null default 0,
  issizlik_isci  numeric(12,2) not null default 0,
  tibbi_isci     numeric(12,2) not null default 0,
  dsmf_isveren   numeric(12,2) not null default 0,
  issizlik_isveren numeric(12,2) not null default 0,
  tibbi_isveren  numeric(12,2) not null default 0,
  odenilib       boolean not null default false,
  yaradildi      timestamptz not null default now(),
  unique (magaza_id, emekdas_id, ay),
  foreign key (emekdas_id, magaza_id) references public.emekdaslar(id, magaza_id) on delete cascade
);

-- RLS, jurnal, hüquqlar (dükan cədvəlləri ilə eyni qayda)
do $$
declare t text;
begin
  foreach t in array array['kontragentler','qaimeler','bank_hesablari','qaime_odenisleri','bank_emeliyyatlari','gomruk','emekdaslar','emek_haqqi']
  loop
    execute format('alter table public.%I enable row level security', t);
    execute format('drop policy if exists oxu on public.%I', t);
    execute format('drop policy if exists elave on public.%I', t);
    execute format('drop policy if exists duzelt on public.%I', t);
    execute format('drop policy if exists sil on public.%I', t);
    execute format($p$create policy oxu on public.%I for select to authenticated
      using (magaza_id = (select public.magazam()) and (select public.rolum()) in ('muhasib','sahibkar'))$p$, t);
    execute format($p$create policy elave on public.%I for insert to authenticated
      with check (magaza_id = (select public.magazam()) and (select public.rolum()) = 'muhasib' and (select public.aktivdir()))$p$, t);
    execute format($p$create policy duzelt on public.%I for update to authenticated
      using (magaza_id = (select public.magazam()) and (select public.rolum()) = 'muhasib' and (select public.aktivdir()))
      with check (magaza_id = (select public.magazam()))$p$, t);
    execute format($p$create policy sil on public.%I for delete to authenticated
      using (magaza_id = (select public.magazam()) and (select public.rolum()) = 'muhasib' and (select public.aktivdir()))$p$, t);
    execute format('drop trigger if exists jurnal_trg on public.%I', t);
    execute format('create trigger jurnal_trg after insert or update or delete on public.%I for each row execute function public.jurnal_yaz()', t);
    execute format('grant select, insert, update, delete on public.%I to authenticated', t);
  end loop;
end $$;
grant usage, select on all sequences in schema public to authenticated;

-- Qaimələr ödəniş vəziyyəti ilə
drop view if exists public.v_qaimeler;
create view public.v_qaimeler with (security_invoker = true) as
select q.*, q.esas + q.edv + q.edvsiz as cem,
       coalesce(o.odenilib, 0) as odenilib, coalesce(o.edv_odenilib, 0) as edv_odenilib,
       q.esas + q.edv + q.edvsiz - coalesce(o.odenilib, 0) as qaliq, o.son_odenis
from public.qaimeler q
left join (select qaime_id, sum(mebleg) odenilib, sum(edv) edv_odenilib, max(tarix) son_odenis
           from public.qaime_odenisleri group by qaime_id) o on o.qaime_id = q.id;
grant select on public.v_qaimeler to authenticated;

-- Ödənişlər qaimə məlumatı ilə (əvəzləşmə və bank çıxarışı üçün)
drop view if exists public.v_qaime_odenisleri;
create view public.v_qaime_odenisleri with (security_invoker = true) as
select o.*, date_trunc('month', o.tarix)::date as ay, q.istiqamet, q.voen, q.kontragent, q.seriya, q.nomre, q.tarix as qaime_tarix,
       q.esas as qaime_esas, q.edv as qaime_edv
from public.qaime_odenisleri o join public.qaimeler q on q.id = o.qaime_id;
grant select on public.v_qaime_odenisleri to authenticated;

