create table if not exists public.abune_odenisleri (
  id        bigint generated by default as identity primary key,
  magaza_id bigint not null references public.magazalar(id) on delete cascade,
  tarix     date not null default ((now() at time zone 'Asia/Baku')::date),
  mebleg    numeric(12,2) not null check (mebleg >= 0),
  aylar     int not null default 1 check (aylar >= 0),
  qeyd      text,
  yaradildi timestamptz not null default now()
);
create index if not exists abune_odenisleri_magaza on public.abune_odenisleri(magaza_id);
alter table public.abune_odenisleri enable row level security;
drop policy if exists admin on public.abune_odenisleri;
create policy admin on public.abune_odenisleri for all to authenticated using ((select public.adminem())) with check ((select public.adminem()));
grant select, insert, update, delete on public.abune_odenisleri to authenticated;
grant usage, select on all sequences in schema public to authenticated;

-- Ödəniş qəbul et: yazır və abunəni uzadır
create or replace function public.admin_odenis(m bigint, mebleg numeric, aylar int, qeyd text) returns date
language plpgsql security definer set search_path = public as $f$
declare d date;
begin
  if not public.adminem() then raise exception 'İcazə yoxdur'; end if;
  insert into abune_odenisleri(magaza_id, mebleg, aylar, qeyd) values (m, coalesce(mebleg, 0), coalesce(aylar, 0), nullif(trim(qeyd), ''));
  update magazalar set abune_bitir = (greatest(abune_bitir, public.bugun()) + make_interval(months => coalesce(aylar, 0)))::date, dayandirilib = false
   where id = m returning abune_bitir into d;
  return d;
end $f$;

drop function if exists public.admin_magazalar();
create function public.admin_magazalar()
returns table(id bigint, ad text, sahib_ad text, telefon text, email text, qeydiyyat timestamptz,
              abune_bitir date, dayandirilib boolean, admin_qeyd text, aktiv boolean,
              uzv_sayi bigint, musteri_sayi bigint, satis_sayi bigint, son_aktivlik timestamptz,
              odenilib numeric, son_odenis date)
language plpgsql stable security definer set search_path = public as $f$
begin
  if not public.adminem() then raise exception 'İcazə yoxdur'; end if;
  return query
  select m.id, m.ad, m.sahib_ad, m.telefon, m.email, m.qeydiyyat, m.abune_bitir, m.dayandirilib, m.admin_qeyd,
         (not m.dayandirilib and m.abune_bitir >= public.bugun()),
         (select count(*) from uzvler u where u.magaza_id = m.id),
         (select count(*) from musteriler x where x.magaza_id = m.id),
         (select count(*) from satislar x where x.magaza_id = m.id),
         (select max(j.zaman) from jurnal j where j.magaza_id = m.id),
         coalesce((select sum(o.mebleg) from abune_odenisleri o where o.magaza_id = m.id), 0),
         (select max(o.tarix) from abune_odenisleri o where o.magaza_id = m.id)
  from magazalar m order by m.qeydiyyat desc;
end $f$;
revoke all on function public.admin_magazalar(), public.admin_odenis(bigint, numeric, int, text) from public, anon;
grant execute on function public.admin_magazalar(), public.admin_odenis(bigint, numeric, int, text) to authenticated;

-- Demo məlumat: boş dükanı nümunə məhsul, müştəri, satış, ödəniş və xərclərlə doldurur
create or replace function public.admin_demo_doldur(m bigint) returns text
language plpgsql security definer set search_path = public as $f$
declare
  adlar text[] := array['Əli','Vüsal','Nigar','Kamran','Leyla','Orxan','Sevinc','Rauf','Günay','Elnur','Aysel','Tural','Səbinə','Fərid','Lalə'];
  soyad text[] := array['Həsənov','Quliyev','Məmmədova','Əliyev','Abbasov','Rzayeva','Babayev','Hüseynov','Kərimova','Nəsirov'];
  yerler text[] := array['Mərkəz','Yeni məhəllə','Stansiya','Bazar yanı','Kənd yolu'];
  mehs text[][] := array[['Künc divan Milano','1450','980','Divanlar'],['Divan-çarpayı Roma','980','650','Divanlar'],['Yataq dəsti Venera','3200','2300','Yataq'],
                         ['Mətbəx dəsti 2.4 m','2100','1500','Mətbəx'],['Mətbəx dəsti 3 m','2700','1900','Mətbəx'],['Şkaf 3 qapılı','1250','850','Şkaflar'],
                         ['Yazı masası','220','150','Masalar'],['Yemək masası + 6 stul','890','600','Masalar'],['Jurnal masası','180','110','Masalar'],['Uşaq otağı dəsti','1750','1200','Yataq']];
  i int; k int; mid bigint; sid bigint; pid bigint; d date; deyer numeric; ilkin numeric; ay numeric; mcount int;
begin
  if not public.adminem() then raise exception 'İcazə yoxdur'; end if;
  if exists (select 1 from satislar where magaza_id = m) then raise exception 'Bu dükanda artıq satış var — demo yalnız boş dükana yazılır'; end if;
  perform setseed(0.42);
  for i in 1..array_length(mehs, 1) loop
    insert into mehsullar(magaza_id, ad, qiymet, maya, kateqoriya, anbar_izle, min_qaliq)
    values (m, mehs[i][1], mehs[i][2]::numeric, mehs[i][3]::numeric, mehs[i][4], true, 2) returning id into pid;
    insert into anbar_hereketleri(magaza_id, mehsul_id, tarix, nov, miqdar, qiymet, techizatci)
    values (m, pid, public.bugun() - 200, 'Mədaxil', 15 + (random() * 10)::int, mehs[i][3]::numeric, 'İstehsalat sexi');
  end loop;
  insert into isciler(magaza_id, ad, vezife, nov, ise_giris, baslangic_maas, satis_faizi) values
    (m, 'Tural Satıcı', 'Satıcı', 'İşçi', public.bugun() - 400, 500, 2), (m, 'Səbinə Kassir', 'Kassir', 'İşçi', public.bugun() - 300, 450, 0),
    (m, 'Fərid Sürücü', 'Sürücü', 'İşçi', public.bugun() - 250, 400, 0);
  for i in 1..30 loop
    insert into musteriler(magaza_id, ad, telefon, unvan)
    values (m, adlar[1 + (i % 15)] || ' ' || soyad[1 + (i % 10)], '050 ' || lpad((1000000 + i * 7919)::text, 7, '0'), yerler[1 + (i % 5)]) returning id into mid;
    for k in 1..(1 + (i % 2)) loop
      d := public.bugun() - (10 + ((i * 37 + k * 11) % 300));
      mcount := 1 + ((i + k) % 10);
      select id into pid from mehsullar where magaza_id = m and ad = mehs[mcount][1];
      deyer := mehs[mcount][2]::numeric; ilkin := round(deyer * (0.1 + (i % 3) * 0.1)); ay := ceil((deyer - ilkin) / (6 + (i % 4) * 3));
      insert into satislar(magaza_id, tarix, musteri_id, mal, deyer, ilkin, ayliq, ilk_odenis, maya, isci_id)
      values (m, d, mid, mehs[mcount][1], deyer, ilkin, ay, (d + interval '1 month')::date, mehs[mcount][3]::numeric,
              (select id from isciler where magaza_id = m and ad = 'Tural Satıcı'))
      returning id into sid;
      insert into satis_mallari(magaza_id, satis_id, mehsul_id, ad, miqdar, qiymet, maya) values (m, sid, pid, mehs[mcount][1], 1, deyer, mehs[mcount][3]::numeric);
      -- ödənişlər: çoxu vaxtında, bəziləri gecikir
      for j in 1..greatest(0, ((public.bugun() - d) / 30) - (case when i % 4 = 0 then 2 else 0 end)) loop
        exit when (select coalesce(sum(mebleg), 0) from satis_odenisleri where satis_id = sid) + ay > deyer - ilkin + 0.01;
        insert into satis_odenisleri(magaza_id, satis_id, tarix, mebleg) values (m, sid, (d + make_interval(months => j))::date + (i % 5), ay);
      end loop;
    end loop;
  end loop;
  for i in 1..24 loop
    insert into rasxodlar(magaza_id, tarix, aciqlama, kim, mebleg, kateqoriya)
    values (m, public.bugun() - i * 12, (array['Dükan kirayəsi','Benzin','İşıq pulu','Daşınma','Reklam'])[1 + i % 5], 'Admin',
            (array[400, 60, 45, 80, 50])[1 + i % 5], (array['Kirayə','Yanacaq','Kommunal','Nəqliyyat','Digər'])[1 + i % 5]);
  end loop;
  return 'Demo məlumat yazıldı';
end $f$;
revoke all on function public.admin_demo_doldur(bigint) from public, anon;
grant execute on function public.admin_demo_doldur(bigint) to authenticated;
