-- Satıcı (işçi) və satış faizi
alter table public.isciler  add column if not exists satis_faizi numeric(5,2) not null default 0 check (satis_faizi >= 0);
alter table public.satislar add column if not exists isci_id bigint;
do $$ begin
  if not exists (select 1 from pg_constraint where conname = 'satislar_isci_fk') then
    alter table public.satislar add constraint satislar_isci_fk foreign key (isci_id, magaza_id)
      references public.isciler(id, magaza_id) on delete set null (isci_id);
  end if;
end $$;
create index if not exists satislar_isci on public.satislar(isci_id);

-- Kassanın günlük bağlanışı
create table if not exists public.kassa_baglanislari (
  id         bigint generated by default as identity primary key,
  magaza_id  bigint not null default public.magazam() references public.magazalar(id) on delete cascade,
  tarix      date not null,
  hesablanan numeric(12,2) not null,
  sayilan    numeric(12,2) not null,
  qeyd       text,
  kim        text,
  yaradildi  timestamptz not null default now(),
  unique (magaza_id, tarix)
);
do $$
declare t text := 'kassa_baglanislari';
begin
  execute format('alter table public.%I enable row level security', t);
  execute format('drop policy if exists oxu on public.%I', t);
  execute format('drop policy if exists elave on public.%I', t);
  execute format('drop policy if exists duzelt on public.%I', t);
  execute format('drop policy if exists sil on public.%I', t);
  execute format($p$create policy oxu on public.%I for select to authenticated
    using (magaza_id = (select public.magazam()) and (select public.rolum()) in ('muhasib','sahibkar'))$p$, t);
  execute format($p$create policy elave on public.%I for insert to authenticated
    with check (magaza_id = (select public.magazam()) and (select public.rolum()) = 'muhasib' and (select public.aktivdir()))$p$, t);
  execute format($p$create policy duzelt on public.%I for update to authenticated
    using (magaza_id = (select public.magazam()) and (select public.rolum()) = 'muhasib' and (select public.aktivdir()))
    with check (magaza_id = (select public.magazam()))$p$, t);
  execute format($p$create policy sil on public.%I for delete to authenticated
    using (magaza_id = (select public.magazam()) and (select public.rolum()) = 'muhasib' and (select public.aktivdir()))$p$, t);
  execute format('drop trigger if exists jurnal_trg on public.%I', t);
  execute format('create trigger jurnal_trg after insert or update or delete on public.%I for each row execute function public.jurnal_yaz()', t);
  execute format('grant select, insert, update, delete on public.%I to authenticated', t);
end $$;
grant usage, select on all sequences in schema public to authenticated;

-- Verilən günün sonunda kassada olmalı olan pul (Kassa səhifəsindəki hesabla eyni qayda)
create or replace function public.kassa_qaliq(t date) returns numeric
language sql stable security invoker set search_path = public as $$
  with b as (
    select coalesce((select nullif(deyer, '')::date from ayarlar where magaza_id = magazam() and acar = 'kassa_baslangic'),
                    (select date_trunc('month', min(tarix))::date from satislar)) as d
  )
  select coalesce((select nullif(deyer, '')::numeric from ayarlar where magaza_id = magazam() and acar = 'kassa_ilkin'), 0)
       + coalesce((select sum(ilkin)  from satislar        where tarix >= (select d from b) and tarix <= t), 0)
       + coalesce((select sum(mebleg) from satis_odenisleri where tarix >= (select d from b) and tarix <= t), 0)
       + coalesce((select sum(case when nov = 'Mədaxil' then mebleg else -mebleg end) from kassa_diger where tarix >= (select d from b) and tarix <= t), 0)
       - coalesce((select sum(mebleg) from rasxodlar       where tarix >= (select d from b) and tarix <= t), 0)
       - coalesce((select sum(mebleg) from isci_odenisleri where nov in ('Avans','Maaş') and tarix >= (select d from b) and tarix <= t), 0)
$$;
grant execute on function public.kassa_qaliq(date) to authenticated;

